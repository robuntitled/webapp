const MICROSTATE_IDS = new Set([
  'andorra',
  'liechtenstein',
  'monaco',
  'san-marino',
  'vaticano',
  'nauru',
  'tuvalu',
  'palau',
  'isole-marshall',
  'kiribati',
]);

export const CONTINENT_COUNTRIES: ComposerDestination[] = SEED.map(
  ([id, label, region, lat, lng, vibe, iso2]) => ({
    id,
    label,
    emoji: flagEmoji(iso2),
    region,
    vibe,
    gradient: REGION_GRADIENT[region],
    lat,
    lng,
    countryCode: iso2,
  })
);

export function countriesInRegion(region: string): ComposerDestination[] {
  return CONTINENT_COUNTRIES.filter((c) => c.region === region);
}

export function isSearchableCountry(id: string): boolean {
  return !MICROSTATE_IDS.has(id);
}

export function findContinentCountry(idOrLabel: string): ComposerDestination | undefined {
  const key = idOrLabel.trim().toLowerCase();
  return CONTINENT_COUNTRIES.find((d) => d.id === key || d.label.toLowerCase() === key);
}
